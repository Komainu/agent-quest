/* =============================================================
   data/room.js — 部屋（室内）
   -------------------------------------------------------------
   kibble のような「1つの掲示板部屋」だけで完結するログ用の舞台。
   data/world.js（街）と同じ約束ごとで書きます。**移動先が複数の
   建物になる街と違い、部屋は1つしかない**ので、歩き回るのは
   「board（依頼板）へ行く」「desk（自分の机）に戻る」
   「dropoff（納品口）へ運ぶ」「inspect（検品台）で判定を受ける」
   の4か所だけです。

   ★ 2026-09-06 (2): 納品と判定は別の場所に
     以前は「bench（検品台）」という1つの家具が、DELIVER（納品）も
     ATTEST（合格／不合格の判定）も両方まとめて引き受けていた。
     「納品する場所が無い。判定する場所も無い」というユーザー報告への
     対応で、南の壁を2つの独立した家具に分け直した：
       dropoff（納品口） … DELIVER された札がまず置かれる場所。
                           まだ誰も判定していない＝合否は分からない。
       inspect（検品台） … ATTEST で✓／✗のスタンプが押される場所。
                           納品口から運ばれてきた札がここで判定される。
     ①出された→②引き受けた→③納品→④判定、の③と④が画面上でも
     別の場所になったことで、「行ったり来たり」に見えていた進み具合が
     「板→納品口→検品台」という一本道として読めるようになる。

   ★ 2026-09-01 全面リサイズ（tile:20 → tile:40）
     実際の kibble ログ（DID 14体・仕事20件規模）で試したところ、
     tile:20 では画面のすべてが数ピクセルしかなく、名札・カード・
     文字が判読不能になった（ユーザー報告：#6#4#9 のような名札の
     重なり）。1マスを倍の40pxにし、部屋の見た目のマス数そのものを
     12列×8行まで絞ることで解決した。

   ★ 2026-09-28(2) 17列×7行 → 15列×7行
     画面下のテロップ枠を撤廃して、縦が 170〜230px 空いた。ところが盤面は
     横に長い（17:7）ので、縦を使い切るには横幅が要り、名簿の列の横では
     それが足りない。列を減らして盤面を縦長寄り（15:7）にし、空いた縦を
     そのまま絵の大きさに回す（1マスもさらに大きく映る）。

   ★ 2026-09-28 20列×8行 → 17列×7行（カメラを主役に寄せる）
     「背景の壁面に対してキャラクターと作業台の占める割合が小さい」
     「あまり変わっていない／魅力的ですっきりした見た目にしてほしい」
     という指摘への対応。canvas の見かけの大きさ（CSS 側の vh 係数）は
     縦の予算でぎりぎりまで使い切っていて、これ以上大きくできない。
     そこで **映すマス数のほうを減らす**：同じ画面幅を 20 マスではなく
     17 マスで分けるので、1マス＝ロボットも札も家具も大きく映る。
     行を 6 まで詰めると、板の下端〜納品口の上端の床が 2 行（80px）に
     なり、ロボットの footprint（88px）が入らなくなる
     （tools/check-world.js の floor band 検査が落ちる）。歩ける床は
     3 行必要なので、7 行がぎりぎりの下限。机の列 A(y=2) と列 B(y=4) の
     あいだの空き行(y=3)も、名札どうしが重ならないようにそのまま残した。

   ★ 2026-09-04 横幅を12列→20列に拡張（「部屋の表示も小さすぎる、
     もっと画面を有効活用してほしい」というユーザー報告への対応）
     縦の高さ予算（画面を1コマも超えさせない、という既存の制約）は
     変えられないので、tile は40pxのまま・行数も8行のまま据え置き、
     横方向だけ広げて「同じ縦予算でもっと横に使う」を実現する。
     board / bench の枠を新しい横幅いっぱいまで広げ、machine desks の
     8マスもその分間隔を広げて配置し直した（歩ける・重複しない・
     どこからでも到達できる、は tools/check-world.js が検証する）。
     view.cols も 20 に合わせてあるので、街と同じくカメラは (0,0) に
     固定のまま＝部屋のどこも常に画面いっぱいに見える。

   ground の文字（1文字 = 1マス = 40px）
     f  床       w  壁（通行止め）

   歩けるのは walkable の文字のマスだけ。
   ============================================================= */
(function (AQ) {
  'use strict';

  AQ.roomWorld = {
    tile: 40,

    /* 20列 × 8行。
       行0・行7＝外周の壁。行1と行6は「床」の文字だが、実際には
       board / dropoff / inspect オブジェクトの足元として通行止めになる
       （objects の x,y,w,h がそのまま通行止め判定に使われるので、
       ここの文字が f でも w でも見た目・通行のどちらも変わらない。
       f にしてあるのは「本当は床がある場所に、家具を置いている」
       という事実をそのまま書いておくため）。 */
    ground: [
      'wwwwwwwwwwwwwww',   // y=0 外周（上）＋掲示板の上半分
      'wfffffffffffffw',   // y=1 掲示板の下半分（board オブジェクトで通行止め）
      'wfffffffffffffw',   // y=2 机の列 A ＋ 掲示板の前に立つ場所
      'wfffffffffffffw',   // y=3 通路（机の列どうしの間・名札がぶつからない間隔）
      'wfffffffffffffw',   // y=4 机の列 B ＋ 納品口・検品台の前に立つ場所
      'wfffffffffffffw',   // y=5 納品口・検品台（dropoff / inspect オブジェクトで通行止め）
      'wwwwwwwwwwwwwww'    // y=6 外周（下）＋納品口・検品台の下半分
    ],

    walkable: 'f',

    /* ---------------------------------------------------------
       部屋に置くもの。x, y, w, h, at は data/world.js と同じ意味。
       板（board）・納品口（dropoff）・検品台（inspect）は、それぞれ
       「枠→タイトル帯→中の札」がひとかたまりの1つのオブジェクトとして
       置く。枠・タイトル帯・貼られた札はすべて render/room.js 側で
       枠の内側に描くので、ここでは位置と大きさだけを決める（文言・
       件数は毎コマ変わるのでここに焼き込まない＝i18n 側で組み立てる）。
       --------------------------------------------------------- */
    objects: [
      /* 依頼板。北の壁いっぱいに構える（未消化の JOB がここに積み上がる）。
         h:2 で壁の行(y=0)と、その手前の床1行(y=1)ぶんの高さを取り、
         「壁に埋め込まれた掲示板」に見えるだけの奥行きを持たせてある。
         w は新しい横幅（20マス）の内側いっぱい（壁を除く18マス）。 */
      { id: 'board', type: 'jobboard', x: 1, y: 0, w: 13, h: 2, at: [7, 2] },

      /* 納品口。南の壁の左半分。DELIVER された札（まだ誰にも判定されて
         いない＝合否不明）はここに置かれる。「投入口の付いた受け皿」の
         見た目にする（render/room.js の drawHatch）。検品台と1マス
         （x=9）の隙間を空けて、見た目にも別の家具だと分かるようにした。 */
      { id: 'dropoff', type: 'dropoff', x: 1, y: 5, w: 6, h: 2, at: [3, 4] },

      /* 検品台。南の壁の右半分。納品口に置かれた札はここへ運ばれて
         ATTEST でスタンプ（合格✓・不合格✗）が押される。以前の bench の
         見た目（鋼板のカウンター＋クリップ留め）をそのまま引き継ぐ。 */
      { id: 'inspect', type: 'inspect', x: 8, y: 5, w: 6, h: 2, at: [11, 4] }
    ],

    places: {
      board:   [7, 2],    // objects.board.at と同じ
      dropoff: [3, 4],    // objects.dropoff.at と同じ
      inspect: [11, 4],   // objects.inspect.at と同じ（机の列Bと同じ行だが、机の座標そのものは避けてある）

      /* 複数エージェント同時表示のための「自分の机」の候補地。
         data/world.js の places.homes と同じ考え方：名前のハッシュから
         1つを選ぶので、同じ名前は常に同じ机に戻る（tools/check-world.js で検証）。
         机は objects に入れていない（歩けるマスのままにしておきたいので、
         自分の机の上にロボットが立てる＝home/idle と同じ扱い。
         idle 用の別プールは持たない＝「待機」も「自分の机で待つ」も
         同じ場所でよく、8マスしかない部屋にもう1系統プールを足すと
         今度はそちらが窮屈になるだけなので、机1本に統一した）。

         列A(y=3)・列B(y=5) の2段、各4マス。横幅が広がったぶん、
         1段の中は x を5ずつ離してある（隣どうしの間に4マスぶんの
         空き＝以前（3マス間隔）よりさらに余裕がある）。列Bは
         dropoff.at（x=4）・inspect.at（x=14）を避けて配置してある。
         段と段の間（y=4）も
         1行まるごと空けてあるので、下の段のロボットの名札が上の段の
         ロボットの足元に届かない。 */
      desks: [
        [2, 2], [4, 2], [10, 2], [12, 2],
        [1, 4], [6, 4], [8, 4], [13, 4]
      ]
    },

    /* 画面に映るマス数。ground の実サイズ（20×8）と完全に一致させて
       あるので、render/room.js のカメラは常に (0,0)＝部屋全体が
       ノーパンで常に画面に収まる。 */
    view: { cols: 15, rows: 7 }
  };

})(window.AQ = window.AQ || {});
